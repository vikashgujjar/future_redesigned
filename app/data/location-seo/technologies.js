const TECHNOLOGIES_BY_SLUG = new Map(TECHNOLOGIES.flatMap((tech) => {
  const entries = [[tech.slug, tech]];
  const keywordSlug = tech.primaryKeywordSlug || slugifyKeyword(tech.primaryKeyword || tech.name);
  if (keywordSlug && keywordSlug !== tech.slug) {
    entries.push([keywordSlug, tech]);
  }
  return entries;
}));

export function getTechnologyBySlug(slug) {
  return TECHNOLOGIES_BY_SLUG.get(slug);
}

export function getTechnologyById(id) {
  return TECHNOLOGIES.find((tech) => tech.id === id) || null;
}

export function slugifyKeyword(keyword) {
  return keyword
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function getTechnologyKeywordSlug(technology) {
  if (!technology) return null;
  return technology.primaryKeywordSlug || slugifyKeyword(technology.primaryKeyword || technology.name);
}

export function getTechnologyLocationPath(technologyOrSlug, countryCode, citySlug) {
  const technology = typeof technologyOrSlug === "string" ? getTechnologyBySlug(technologyOrSlug) : technologyOrSlug;
  if (!technology) return null;
  const keywordSlug = getTechnologyKeywordSlug(technology);
  if (!keywordSlug) return null;
  return `/${countryCode}/${keywordSlug}-in-${citySlug}`;
}
